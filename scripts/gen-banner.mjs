// Renders the banner lettering once, at development time, into src/bannerArt.ts.
//
// The card only ever draws one word in two fonts, so shipping figlet (18 MB of
// fonts) to every `npx` run to do it is waste. Run `npm run gen:banner` after
// changing the word or the fonts; test/bannerArt.test.ts fails if the committed
// file drifts from what figlet produces.

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import figlet from 'figlet';

export const TEXT = 'brignano';
export const FONTS = ['ANSI Shadow', 'Small'];

// Figlet's raw lines per font, untrimmed: src/banner.ts squares them up.
export function renderArt() {
  return Object.fromEntries(
    FONTS.map((font) => [font, figlet.textSync(TEXT, { font }).split('\n')]),
  );
}

const target = fileURLToPath(new URL('../src/bannerArt.ts', import.meta.url));

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const source = [
    '// Generated by `npm run gen:banner` (scripts/gen-banner.mjs). Do not edit.',
    '',
    `export const bannerText = ${JSON.stringify(TEXT)};`,
    '',
    `export const bannerArt = ${JSON.stringify(renderArt(), null, 2)} as const;`,
    '',
  ].join('\n');
  writeFileSync(target, source);
  // Let Biome settle quotes and wrapping so the file passes `npm run lint`.
  execFileSync('npx', ['biome', 'format', '--write', target], { stdio: 'inherit' });
}
